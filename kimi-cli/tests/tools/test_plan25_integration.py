# ═══════════════════════════════════════════════════════════════════════════
# Drift notes (file_mtime.mark_dirty wired before the write)
# ═══════════════════════════════════════════════════════════════════════════


async def test_write_drift_note_after_external_change(
    read_file_tool, write_file_tool: WriteFile, session: Session, temp_work_dir: KaosPath
):
    import os
    import time
    from pathlib import Path

    from kimi_cli.tools.file.read import Params as ReadParams

    f = temp_work_dir / "drift.txt"
    await f.write_text("v1\n")
    await read_file_tool(ReadParams(path=str(f)))  # establishes read baseline
    # external modification after the read
    p = Path(str(f))
    p.write_text("v1\nexternally added\n", encoding="utf-8")
    future = time.time() + 10
    os.utime(p, (future, future))
    result = await write_file_tool(
        WriteParams(file_path=str(f), content="v2\n", mode="overwrite")
    )
    assert not result.is_error, result.message
    assert "file changed since last read" in result.message
    # snapshot recorded the pre-overwrite (drifted) content
    head = get_file_snapshot_store(session).head(str(f))
    assert head is not None
    assert head.text == "v2\n"


