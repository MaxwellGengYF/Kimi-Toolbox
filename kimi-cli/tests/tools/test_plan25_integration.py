# ═══════════════════════════════════════════════════════════════════════════
# FS-cache invalidation after write/edit (gitignore freshness)
# ═══════════════════════════════════════════════════════════════════════════


async def test_write_gitignore_invalidates_glob_cache(
    write_file_tool: WriteFile, temp_work_dir: KaosPath
):
    from kimi_cli.tools.file import glob as glob_mod
    from pathlib import Path

    root = str(Path(str(temp_work_dir)).resolve())
    # prime the glob cache for this root
    gi = temp_work_dir / ".gitignore"
    await gi.write_text("*.log\n")
    glob_mod._get_gitignore_rules(Path(str(temp_work_dir)).resolve())
    assert root in glob_mod._GITIGNORE_CACHE

    # rewrite the gitignore through the write tool → cache busted
    result = await write_file_tool(
        WriteParams(file_path=str(gi), content="*.tmp\n", mode="overwrite")
    )
    assert not result.is_error
    assert root not in glob_mod._GITIGNORE_CACHE


# ═══════════════════════════════════════════════════════════════════════════
# Plan 25 §9: conflict-resolution writes share the success-path hooks
# ═══════════════════════════════════════════════════════════════════════════


OURS = "<" * 7
SEP = "=" * 7
THEIRS = ">" * 7


def _conflicted(before="top", after="bottom"):
    return f"{before}\n{OURS} HEAD\nours side\n{SEP}\ntheirs side\n{THEIRS} feature/x\n{after}\n"


async def test_conflict_resolve_records_snapshot(
    read_file_tool, write_file_tool: WriteFile, session: Session, temp_work_dir: KaosPath
):
    from kimi_cli.tools.file.read import Params as ReadParams

    f = temp_work_dir / "conf.txt"
    await f.write_bytes(_conflicted().encode("utf-8"))
    await read_file_tool(ReadParams(path=str(f)))  # registers the block
    result = await write_file_tool(
        WriteParams(file_path=f"{f}:conflict://1", content="@ours", mode="overwrite")
    )
    assert not result.is_error, result.message
    head = get_file_snapshot_store(session).head(str(f))
    assert head is not None
    assert head.text == "top\nours side\nbottom\n"


async def test_conflict_resolve_invalidates_gitignore_cache(
    read_file_tool, write_file_tool: WriteFile, session: Session, temp_work_dir: KaosPath
):
    """Resolving a conflict inside a .gitignore busts the glob cache (§9 hooks)."""
    from pathlib import Path

    from kimi_cli.tools.file import glob as glob_mod
    from kimi_cli.tools.file.read import Params as ReadParams

    root = str(Path(str(temp_work_dir)).resolve())
    gi = temp_work_dir / ".gitignore"
    await gi.write_bytes(_conflicted(before="*.log", after="*.tmp").encode("utf-8"))
    glob_mod._get_gitignore_rules(Path(str(temp_work_dir)).resolve())
    assert root in glob_mod._GITIGNORE_CACHE
    await read_file_tool(ReadParams(path=str(gi)))
    result = await write_file_tool(
        WriteParams(file_path=f"{gi}:conflict://1", content="@ours", mode="overwrite")
    )
    assert not result.is_error, result.message
    assert root not in glob_mod._GITIGNORE_CACHE


